package layout

// base16 is the 16 standard ANSI colors.
var base16 = [16][3]uint8{
	{0x45, 0x47, 0x5a}, {0xf3, 0x8b, 0xa8}, {0xa6, 0xe3, 0xa1}, {0xf9, 0xe2, 0xaf},
	{0x89, 0xb4, 0xfa}, {0xf5, 0xc2, 0xe7}, {0x94, 0xe2, 0xd5}, {0xba, 0xc2, 0xde},
	{0x58, 0x5b, 0x70}, {0xf3, 0x8b, 0xa8}, {0xa6, 0xe3, 0xa1}, {0xf9, 0xe2, 0xaf},
	{0x89, 0xb4, 0xfa}, {0xf5, 0xc2, 0xe7}, {0x94, 0xe2, 0xd5}, {0xa6, 0xad, 0xc8},
}

var cube = [6]uint8{0, 95, 135, 175, 215, 255}

// palette maps an xterm 256-color index to RGB.
func palette(i int) [3]uint8 {
	switch {
	case i < 0:
		return [3]uint8{}
	case i < 16:
		return base16[i]
	case i < 232:
		i -= 16
		return [3]uint8{cube[i/36], cube[i/6%6], cube[i%6]}
	case i < 256:
		v := uint8(8 + (i-232)*10)
		return [3]uint8{v, v, v}
	}
	return [3]uint8{0xff, 0xff, 0xff}
}
